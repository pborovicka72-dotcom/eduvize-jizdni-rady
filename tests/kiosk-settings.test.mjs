import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../transport-settings.js',import.meta.url),'utf8');
const events={},values=new Map(),window={localStorage:{getItem:k=>values.get(k)||null},addEventListener:(name,fn)=>events[name]=fn,setInterval:fn=>events.poll=fn};
vm.runInNewContext(source,{window,URLSearchParams});
const api=window.EduvizeTransportSettings,key='eduvize-pid-config';
values.set(key,JSON.stringify({stops:['Nová zastávka','Náměstí'],source:'pid',minutes:'90',types:['tram']}));
const legacy='?stops=Původní&viewMode=kiosk&unknown=keep';
assert.equal(api.query(legacy).toString(),new URLSearchParams(legacy).toString());
assert.equal(api.query('?viewMode=kiosk').has('stops'),false);
const live='?transport_settings=browser&viewMode=kiosk&interaction=interactive&unknown=keep';
assert.equal(api.query(live).get('stops'),'Nová zastávka|Náměstí');
assert.equal(api.query(live).get('unknown'),'keep');
assert.equal(api.query(live).get('viewMode'),'kiosk');
let reloads=0;api.watch(live,()=>reloads++);events.poll();assert.equal(reloads,0);
values.set(key,JSON.stringify({stops:['Jiná'],source:'cz_gtfs',types:['train']}));
events.storage({key});assert.equal(reloads,1);events.poll();assert.equal(reloads,1);
assert.equal(api.query(live).get('source'),'cz_gtfs');
values.set(key,JSON.stringify({profileId:'other',stops:['Cizí škola']}));
assert.equal(api.query(live+'&edu-profile=school').has('stops'),false);
values.set(key+':school',JSON.stringify({profileId:'school',stops:['Moje škola']}));
assert.equal(api.query(live+'&edu-profile=school').get('stops'),'Moje škola');
values.set(key,'invalid JSON');assert.equal(api.query(live).has('stops'),false);
assert.equal(api.query(live,{getItem(){throw Error('Storage blocked');}}).has('stops'),false);
console.log('Kiosk defaults follow saved stops, updates trigger one reload, explicit legacy links remain pinned, profile isolation and blocked storage passed.');
